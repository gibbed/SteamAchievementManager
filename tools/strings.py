# -*- coding: utf-8 -*-
"""Maintains the translations in SAM.App/Strings.

    python tools/strings.py

- generates de-CH.json from de.json (ss instead of ß, «guillemets»)
- generates sr-Cyrl.json from sr-Latn.json (Latin -> Cyrillic transliteration)
- checks every language file against en.json: same keys, same placeholders, nothing empty
- generates SAM.App/Localization/Strings.g.cs (one property or method per key)

Exits with code 1 if a file is incomplete.
"""
import io
import json
import os
import re
import sys
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STRINGS = os.path.join(ROOT, "SAM.App", "Strings")
GENERATED = os.path.join(ROOT, "SAM.App", "Localization", "Strings.g.cs")

# Translations that must exist (see AppLanguage.cs)
EXPECTED = [
    "en", "de", "de-CH", "lb", "nl", "fr", "es", "pt-BR", "pt-PT", "it", "da", "sv", "nb", "fi", "is",
    "pl", "cs", "sk", "hu", "sl", "hr", "bs", "sr-Latn", "sr-Cyrl", "mk", "sq", "el", "bg", "ro", "uk",
    "be", "et", "lv", "lt", "mt", "tr", "ru", "ja", "zh-Hans", "zh-Hant", "ko", "id", "th", "vi", "ms",
    "ar", "he",
]

PLACEHOLDER = re.compile(r"\{\d+\}")


def load(name):
    with io.open(os.path.join(STRINGS, name + ".json"), encoding="utf-8") as f:
        return json.load(f, object_pairs_hook=OrderedDict)


def save(name, data, source):
    header_note = "generated by tools/strings.py from %s.json - do not edit by hand" % source
    data_with_note = OrderedDict([("_generated", header_note)])
    data_with_note.update(data)
    text = json.dumps(data_with_note, ensure_ascii=False, indent=2)
    with io.open(os.path.join(STRINGS, name + ".json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text + "\n")


def swiss_german(text):
    text = text.replace("ß", "ss")
    return re.sub(r"»([^«»]*)«", r"«\1»", text)


# Serbian transliteration. Words with digits, dots or in PROTECTED stay Latin.
LATIN_TO_CYRILLIC = [
    ("Dž", "Џ"), ("DŽ", "Џ"), ("dž", "џ"), ("Lj", "Љ"), ("LJ", "Љ"), ("lj", "љ"), ("Nj", "Њ"), ("NJ", "Њ"), ("nj", "њ"),
]
SINGLE = dict(zip("abcčćdđefghijklmnoprsštuvzžABCČĆDĐEFGHIJKLMNOPRSŠTUVZŽ",
                  "абцчћдђефгхијклмнопрсштувзжАБЦЧЋДЂЕФГХИЈКЛМНОПРСШТУВЗЖ"))
PROTECTED = {"Steam", "Steam-a", "Steamu", "Steamom", "Achievement", "Manager", "Spacewar", "ID", "Ctrl", "Family", "Sharing", "gib", "DLC"}


def serbian_cyrillic(text):
    def transliterate(word):
        for latin, cyrillic in LATIN_TO_CYRILLIC:
            word = word.replace(latin, cyrillic)
        return "".join(SINGLE.get(ch, ch) for ch in word)

    def convert_word(match):
        word = match.group(0)
        # Brand names stay Latin, the Cyrillic ending is appended: Steamom -> Steam-ом
        for brand in ("Steam", "Windows", "ID"):
            if word.startswith(brand) and word != brand:
                rest = word[len(brand):].lstrip("-")
                if rest.isalpha():
                    return brand + "-" + transliterate(rest)
        if word in PROTECTED or any(ch.isdigit() for ch in word) or word.split("-")[0] in PROTECTED:
            return word
        return transliterate(word)

    # Category names as in the Steam collections stay English.
    parts = re.split(r"(\{\d+\}|Profile Features Limited|Not 100 % Anymore|Can't Finish|\bUG\b|Ctrl\+\w+|\S*[./]\S*\.\S+|steamclient64\.dll|gib\.me|store\.steampowered\.com/app/480)", text)
    out = []
    for i, part in enumerate(parts):
        if i % 2 == 1:
            out.append(part)
        else:
            out.append(re.sub(r"[A-Za-zČčĆćĐđŠšŽž][\w\-ČčĆćĐđŠšŽž]*", convert_word, part))
    return "".join(out)


def generate_accessors(reference):
    lines = [
        "// <auto-generated>",
        "// Generated by tools/strings.py from SAM.App/Strings/en.json - do not edit by hand.",
        "// </auto-generated>",
        "",
        "namespace SAM.App.Localization;",
        "",
        "public static partial class Strings",
        "{",
    ]
    for key, value in reference.items():
        count = len(set(PLACEHOLDER.findall(value)))
        summary = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        lines.append("    /// <summary>%s</summary>" % summary)
        if count == 0:
            lines.append('    public static string %s => Get("%s");' % (key, key))
        else:
            params = ", ".join("object arg%d" % i for i in range(count))
            args = ", ".join("arg%d" % i for i in range(count))
            lines.append('    public static string %s(%s) => Format("%s", %s);' % (key, params, key, args))
        lines.append("")
    lines[-1] = "}"
    with io.open(GENERATED, "w", encoding="utf-8-sig", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    reference = load("en")

    save("de-CH", OrderedDict((k, swiss_german(v)) for k, v in load("de").items()), "de")

    if os.path.exists(os.path.join(STRINGS, "sr-Latn.json")):
        save("sr-Cyrl", OrderedDict((k, serbian_cyrillic(v)) for k, v in load("sr-Latn").items()), "sr-Latn")

    errors = 0
    present = sorted(f[:-5] for f in os.listdir(STRINGS) if f.endswith(".json"))

    for name in EXPECTED:
        if name not in present:
            print("MISSING %s.json" % name)
            errors += 1

    for name in present:
        if name not in EXPECTED:
            print("UNKNOWN %s.json (not in EXPECTED / AppLanguage)" % name)
            errors += 1
            continue

        data = load(name)
        data.pop("_generated", None)
        missing = [k for k in reference if k not in data]
        extra = [k for k in data if k not in reference]
        bad = [k for k in reference if k in data and
               sorted(set(PLACEHOLDER.findall(data[k]))) != sorted(set(PLACEHOLDER.findall(reference[k])))]
        empty = [k for k in data if not str(data[k]).strip()]

        problems = []
        if missing:
            problems.append("missing: " + ", ".join(missing))
        if extra:
            problems.append("extra: " + ", ".join(extra))
        if bad:
            problems.append("placeholders: " + ", ".join(bad))
        if empty:
            problems.append("empty: " + ", ".join(empty))

        if problems:
            errors += 1
            print("ERROR   %-8s %s" % (name, " | ".join(problems)))

    generate_accessors(reference)
    print("%d translations, %d keys, %d with errors" % (len(present), len(reference), errors))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
